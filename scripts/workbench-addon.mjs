#!/usr/bin/env node
// Puts the Atlas add-on (prices and the financial tabs) and the encrypted price book into the workbench page.
//
// The add-on lives in scripts/workbench-addon/ (crypto.js, addon.js, addon.css) and the price book in
// assets/workbench/pricebook.enc.json. Both are copied into assets/workbench/workbench.html between marker
// comments, so the page stays a single file that works offline. scrub-workbench.mjs runs this as its last step;
// run it on its own after changing the add-on or the price book (the workbench source file is not needed):
//
//   node scripts/workbench-addon.mjs [workbench.html]      (default: assets/workbench/workbench.html)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_BOOK } from './pricebook.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'scripts', 'workbench-addon');
export const DEFAULT_PAGE = join(ROOT, 'assets', 'workbench', 'workbench.html');

const JS_BEGIN = '/* ATLAS-ADDON:BEGIN';
const JS_END = '/* ATLAS-ADDON:END */';
const CSS_BEGIN = '/* ATLAS-ADDON-CSS:BEGIN';
const CSS_END = '/* ATLAS-ADDON-CSS:END */';
const INIT = '/* ============================ Init ============================ */';
const NOTE = 'generated by scripts/workbench-addon.mjs from scripts/workbench-addon/ and assets/workbench/pricebook.enc.json; do not edit here */';

/** The add-on sources and the encrypted price book, as committed. */
export function readAddon({ book = DEFAULT_BOOK } = {}) {
  const read = (f) => readFileSync(join(SRC, f), 'utf8').trim();
  const env = JSON.parse(readFileSync(book, 'utf8'));
  for (const k of ['salt', 'iv', 'data']) if (typeof env[k] !== 'string' || /[^a-p]/.test(env[k])) throw new Error(`workbench-addon: price book field "${k}" is malformed`);
  return { js: `${read('crypto.js')}\n${read('addon.js')}`, css: read('addon.css'), env };
}

/** The page with the add-on inserted (first run) or replaced (every later run). */
export function injectAddon(html, { js, css, env }) {
  const envOut = { format: env.format, kdf: env.kdf, iterations: env.iterations, cipher: env.cipher, salt: env.salt, iv: env.iv, data: env.data };
  const jsBlock = `${JS_BEGIN} ${NOTE}\nvar FIN_ENV=${JSON.stringify(envOut)};\n${js}\n${JS_END}\n`;
  const cssBlock = `${CSS_BEGIN} ${NOTE}\n${css}\n${CSS_END}\n`;
  const place = (src, begin, end, block, anchor) => {
    const i = src.indexOf(begin);
    if (i >= 0) {
      const j = src.indexOf(end, i);
      if (j < 0) throw new Error(`workbench-addon: "${begin}" has no end marker`);
      return src.slice(0, i) + block + src.slice(j + end.length + (src[j + end.length] === '\n' ? 1 : 0));
    }
    const at = src.indexOf(anchor);
    if (at < 0 || src.indexOf(anchor, at + 1) >= 0) throw new Error(`workbench-addon: expected exactly one "${anchor}" in the page`);
    return src.slice(0, at) + block + src.slice(at);
  };
  let out = place(html, JS_BEGIN, JS_END, jsBlock, INIT);
  out = place(out, CSS_BEGIN, CSS_END, cssBlock, '</style>');
  return out;
}

/** The embedded price book (or null), for checks. */
export function embeddedEnv(html) {
  const m = html.match(/\nvar FIN_ENV=(\{[^\n]*\});\n/);
  return m ? JSON.parse(m[1]) : null;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const page = process.argv[2] || DEFAULT_PAGE;
  const html = readFileSync(page, 'utf8');
  const out = injectAddon(html, readAddon());
  writeFileSync(page, out);
  console.log(`${out === html ? 'unchanged' : 'updated'} ${page}`);
}
